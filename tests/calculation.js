function near(actual, expected, tol, msg) {
  const a = Number(actual);
  if (!Number.isFinite(a) || Math.abs(a - expected) > tol) {
    console.error('ПРОВАЛ calculation.js: ' + msg + ' (получено ' + actual + ', ожидалось ' + expected + ')');
    process.exit(1);
  }
}

